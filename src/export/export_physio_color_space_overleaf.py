#!/usr/bin/env python3
"""
LaTeX tables (tabular): CCC, PCC, RMSE, SAGR × (V/A) × color space — mean ± SE
over participants (MABL-ME *_fan.json).

Writes a minimal standalone .tex (compile to PDF) and an _input.tex snippet
(\\input into your paper).

  python3 export_physio_color_space_overleaf.py \\
    --data-dir /home/mabl-main/results/emotion_batch_data \\
    --out /home/mabl-main/results/emotion_batch_data/fig_physio_color_spaces.tex
"""
from __future__ import annotations

import argparse
import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np

SPACE_ORDER = ["rgb", "ycbcr", "xyz", "lab"]
SPACE_LABELS_TEX = ["RGB", "YCbCr", "XYZ", "LAB"]

METRIC_SPECS: List[Tuple[str, List[str], str, str]] = [
    ("ccc_v", ["ccc_valence"], r"CCC$_V$", "ccc"),
    ("ccc_a", ["ccc_arousal"], r"CCC$_A$", "ccc"),
    ("pcc_v", ["pearson_valence", "pcc_valence"], r"PCC$_V$", "pcc"),
    ("pcc_a", ["pearson_arousal", "pcc_arousal"], r"PCC$_A$", "pcc"),
    ("rmse_v", ["rmse_valence"], r"RMSE$_V$", "rmse"),
    ("rmse_a", ["rmse_arousal"], r"RMSE$_A$", "rmse"),
    ("sagr_v", ["sagr_valence"], r"SAGR$_V$", "sagr"),
    ("sagr_a", ["sagr_arousal"], r"SAGR$_A$", "sagr"),
]

ALL_KEYS = [s[0] for s in METRIC_SPECS]


def mean_se(xs: List[float]) -> Tuple[float, float]:
    a = np.asarray(xs, dtype=np.float64)
    a = a[np.isfinite(a)]
    if len(a) == 0:
        return float("nan"), float("nan")
    m = float(np.mean(a))
    if len(a) < 2:
        return m, 0.0
    se = float(np.std(a, ddof=1) / math.sqrt(len(a)))
    return m, se


def pull(comp: Dict[str, Any], keys: List[str]) -> Any:
    for k in keys:
        if k in comp and comp[k] is not None:
            return comp[k]
    return None


def load_by_space(data_dir: Path) -> Tuple[Dict[str, Dict[str, List[float]]], int]:
    by_space: Dict[str, Dict[str, List[float]]] = defaultdict(
        lambda: {k: [] for k in ALL_KEYS}
    )
    n = 0
    for path in sorted(data_dir.glob("*_fan.json")):
        data = json.loads(path.read_text())
        cs = (data.get("color_space") or "").lower().strip()
        if cs not in SPACE_ORDER:
            continue
        comp = data.get("comparison") or {}
        if "note" in comp and "n_paired" not in comp:
            continue
        for dst, keys, _, _ in METRIC_SPECS:
            v = pull(comp, keys)
            if isinstance(v, (int, float)) and math.isfinite(float(v)):
                by_space[cs][dst].append(float(v))
        n += 1
    return by_space, n


def cell(m: float, se: float) -> str:
    if not math.isfinite(m):
        return "---"
    if not math.isfinite(se):
        se = 0.0
    return f"${m:.3f} \\pm {se:.3f}$"


def emit_tex(
    by_space: Dict[str, Dict[str, List[float]]],
    n_files: int,
    out_path: Path,
) -> Tuple[int, Path]:
    counts = [len(by_space[s]["ccc_v"]) for s in SPACE_ORDER]
    n_p = min(counts) if counts else 0

    col_heads = " & ".join(h for _, _, h, _ in METRIC_SPECS)
    rows: List[str] = []
    for s, lab in zip(SPACE_ORDER, SPACE_LABELS_TEX):
        cells = [cell(*mean_se(by_space[s][k])) for k, _, _, _ in METRIC_SPECS]
        rows.append(f"    {lab} & " + " & ".join(cells) + r" \\")
    body = "\n".join(rows)

    col_spec = "l" + "c" * len(METRIC_SPECS)

    tabular = f"""\\begin{{tabular}}{{@{{}}{col_spec}@{{}}}}
    \\toprule
    Space & {col_heads} \\\\
    \\midrule
{body}
    \\bottomrule
\\end{{tabular}}"""

    cap = (
        f"External validation by input color space. "
        f"Mean $\\pm$ SE over $N={n_p}$ participants per space "
        f"({n_files} result JSON files). "
        r"Metrics are trial-level per participant, then averaged; "
        r"SE is over participants."
    )

    standalone = (
        "% Auto-generated by export_physio_color_space_overleaf.py\n"
        "\\documentclass[11pt]{article}\n"
        "\\usepackage{booktabs}\n"
        "\\usepackage[margin=1in]{geometry}\n"
        "\n"
        "\\begin{document}\n"
        "\n"
        "\\begin{table}[ht]\n"
        "\\centering\n"
        "\\footnotesize\n"
        "\\setlength{\\tabcolsep}{4pt}\n"
        + tabular
        + "\n"
        + f"\\caption{{{cap}}}\n"
        + "\\label{tab:physio-color-spaces}\n"
        + "\\end{table}\n"
        + "\n"
        + "\\end{document}\n"
    )

    snippet = (
        "% \\input after: \\usepackage{booktabs}\n"
        "% (table* suits two-column IEEE; use table if single-column.)\n"
        "\n"
        "\\begin{table*}[t]\n"
        "\\centering\n"
        "\\footnotesize\n"
        "\\setlength{\\tabcolsep}{3pt}\n"
        + tabular
        + "\n"
        + f"\\caption{{{cap}}}\n"
        + "\\label{tab:physio-color-spaces}\n"
        + "\\end{table*}\n"
    )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(standalone, encoding="utf-8")

    snippet_path = out_path.with_name(out_path.stem + "_input.tex")
    snippet_path.write_text(snippet, encoding="utf-8")

    return n_p, snippet_path


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Export LaTeX tables (mean ± SE) for color-space metrics"
    )
    ap.add_argument("--data-dir", type=Path, required=True)
    ap.add_argument(
        "--out",
        type=Path,
        required=True,
        help="Path to standalone .tex (article + table)",
    )
    args = ap.parse_args()

    by_space, n_files = load_by_space(args.data_dir)
    if n_files == 0:
        raise SystemExit(f"No usable *_fan.json under {args.data_dir}")

    n_p, snippet_path = emit_tex(by_space, n_files, args.out)

    print(f"Wrote {args.out} (standalone table)")
    print(f"Wrote {snippet_path} (\\input for main paper; needs booktabs)")
    print(f"N={n_p} participants per space, {n_files} JSON files.\n")
    print("## Mean ± SE (stdout check)")
    for key, _, title, _ in METRIC_SPECS:
        parts = []
        for s, lab in zip(SPACE_ORDER, SPACE_LABELS_TEX):
            m, sed = mean_se(by_space[s][key])
            parts.append(f"{lab}={m:.4f}±{sed:.4f}")
        print(f"  {title}: " + "  ".join(parts))


if __name__ == "__main__":
    main()
